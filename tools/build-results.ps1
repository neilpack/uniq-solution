<#
.SYNOPSIS
  Combines results/emails/*.json (one file per processed email) into:
    results/results.csv  - the submission table: email_id, category, priority, needs_human, quote, draft_reply
    results/results.js   - full data for the dashboard (index.html). Loads straight from file://, no server needed.
  powershell -ExecutionPolicy Bypass -File tools/build-results.ps1
#>
$ErrorActionPreference = "Stop"
$root = Resolve-Path (Join-Path $PSScriptRoot "..")
$emailDir = Join-Path $root "results\emails"
$csvOut = Join-Path $root "results\results.csv"
$jsOut = Join-Path $root "results\results.js"
$ordersCsv = Join-Path $root "packet\orders.csv"
$pricing = Get-Content -Raw -Encoding UTF8 (Join-Path $root "data\pricing.json") | ConvertFrom-Json

$required = @("email_id", "category", "priority", "needs_human", "needs_human_reason", "quote", "draft_reply")
$categories = @("Custom Quote", "Stock Order / Product Question", "Order Status", "Damage / Complaint", "Return / Refund", "Billing / Terms", "Spam / Phishing", "Vendor Pitch", "Feedback / Praise")

$items = @()
$problems = @()
foreach ($f in (Get-ChildItem -Path $emailDir -Filter *.json | Sort-Object Name)) {
  $o = Get-Content -Raw -Encoding UTF8 $f.FullName | ConvertFrom-Json
  foreach ($k in $required) { if ($null -eq $o.$k) { $problems += "$($f.Name): missing '$k'" } }
  if ($categories -notcontains $o.category) { $problems += "$($f.Name): unknown category '$($o.category)'" }
  if ($o.priority -notmatch '^P[1-4]$') { $problems += "$($f.Name): bad priority '$($o.priority)'" }
  if ($o.needs_human -notmatch '^(Yes|No)$') { $problems += "$($f.Name): needs_human must be Yes or No" }
  $items += , $o
}
if ($problems.Count -gt 0) { $problems | ForEach-Object { Write-Host "WARNING: $_" -ForegroundColor Yellow } }

# Natural sort: E01..E20, then later IDs
$items = @($items | Sort-Object @{ Expression = { [regex]::Replace($_.email_id, '\d+', { param($m) $m.Value.PadLeft(6, '0') }) } })

# ---- CSV (exact submission columns) ----
$rows = $items | ForEach-Object {
  [pscustomobject][ordered]@{
    email_id    = $_.email_id
    category    = $_.category
    priority    = $_.priority
    needs_human = "$($_.needs_human) - $($_.needs_human_reason)"
    quote       = $_.quote
    draft_reply = $_.draft_reply
  }
}
$rows | Export-Csv -Path $csvOut -NoTypeInformation -Encoding UTF8

# ---- JS for the dashboard ----
$orders = @()
if (Test-Path $ordersCsv) { $orders = @(Import-Csv $ordersCsv) }
$payload = [ordered]@{
  generated_at = (Get-Date).ToString("yyyy-MM-dd HH:mm")
  today        = $pricing.today
  emails       = $items
  orders       = $orders
}
$json = ConvertTo-Json -InputObject $payload -Depth 10
$js = "// Generated by tools/build-results.ps1. Do not edit by hand; edit results/emails/*.json and rebuild.`n" +
      "window.UNIQ_RESULTS = $json;`n"
[System.IO.File]::WriteAllText($jsOut, $js, (New-Object System.Text.UTF8Encoding($false)))

$byP = $items | Group-Object priority | Sort-Object Name | ForEach-Object { "$($_.Name)=$($_.Count)" }
$human = @($items | Where-Object { $_.needs_human -eq "Yes" }).Count
Write-Host "Built $($items.Count) emails -> results/results.csv, results/results.js  ($($byP -join ', '); needs human: $human)"
